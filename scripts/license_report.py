#!/usr/bin/env python3
"""Dependency licence report. Needs `cargo` and `npm ci` already run (CI does both).
  python3 scripts/license_report.py            -> writes THIRD_PARTY_LICENSES.md, exits 1 on a copyleft licence
Rust: `cargo metadata` (licence field of every crate in the build graph). npm: package-lock.json "license" fields."""
import json, os, subprocess, sys, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DENY = ("GPL", "AGPL", "SSPL", "BUSL")   # LGPL is reviewed manually, not auto-denied
def deny(l): return any(t in l.replace("LGPL", "") for t in DENY)

rows = collections.defaultdict(set); bad = []
lock = json.load(open(os.path.join(ROOT, "package-lock.json")))
for path, p in lock["packages"].items():
    if not path: continue
    name = path.split("node_modules/")[-1]; lic = str(p.get("license") or "UNKNOWN")
    rows["npm"].add((name, p.get("version", ""), lic))
    if deny(lic): bad.append((name, lic))
try:
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1"], cwd=os.path.join(ROOT, "src-tauri")))
    for p in meta["packages"]:
        if p["name"] == "netguard": continue
        lic = p.get("license") or p.get("license_file") or "UNKNOWN"
        rows["cargo"].add((p["name"], p["version"], lic))
        if deny(lic): bad.append((p["name"], lic))
except Exception as e:
    print("WARNING: cargo metadata unavailable, Rust licences NOT checked:", e)
out = ["# Third-party licences (generated by scripts/license_report.py)\n"]
for eco, items in rows.items():
    out.append(f"\n## {eco}: {len(items)} packages\n\n| Package | Version | Licence |\n|---|---|---|")
    out += [f"| {n} | {v} | {l} |" for n, v, l in sorted(items)]
open(os.path.join(ROOT, "THIRD_PARTY_LICENSES.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
summary = collections.Counter(l for items in rows.values() for _, _, l in items)
for l, c in summary.most_common(): print(f"{c:5d}  {l}")
if bad: print("COPYLEFT/RESTRICTED:", bad); sys.exit(1)
print("No GPL/AGPL/SSPL/BUSL licences found in the checked dependency graph.")
